def _read_gitignore(root: Path) -> list[str]:
    """Read .gitignore patterns (simple, line-based)."""
    patterns: list[str] = []
    gi = root / ".gitignore"
    if gi.is_file():
        try:
            for line in gi.read_text(encoding="utf-8", errors="ignore").splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    patterns.append(line.rstrip("/"))
        except OSError:
            pass
    return patterns


def _matches_ignore(rel: str, patterns: list[str]) -> bool:
    parts = rel.replace("\\", "/").split("/")
    for p in patterns:
        p = p.strip("/")
        if not p:
            continue
        if p in parts:
            return True
        # simple suffix/glob
        if p.endswith("/*") and rel.startswith(p[:-1]):
            return True
        if p.startswith("*.") and rel.endswith(p[1:]):
            return True
        if p == rel or rel.startswith(p + "/"):
            return True
    return False


def classify_file(path: Path, size: int) -> tuple[FileCategory, str, bool]:
    """Classify a file into a category + language, and detect binary."""
    name = path.name
    lower = name.lower()
    ext = path.suffix.lower()

    if ext in _BINARY_EXTENSIONS:
        return FileCategory.ASSET, "", True

    # Language detection via extension.
    language = _EXT_TO_LANG.get(ext, "")

    # Category inference.
    if ext in {".md", ".markdown", ".rst"} or lower in {"readme", "readme.md"}:
        category = FileCategory.DOC
    elif lower in {"dockerfile"} or ext in {".yml", ".yaml", ".toml", ".ini", ".cfg", ".conf", ".env"}:
        category = FileCategory.CONFIG
    elif name in {"requirements.txt", "package.json", "go.mod", "go.sum", "cargo.toml",
                  "pom.xml", "build.gradle", "pyproject.toml", "setup.py", "gemfile",
                  "composer.json", "pubspec.yaml"}:
        category = FileCategory.CONFIG
    elif "test" in lower or lower.endswith("test.py") or lower.startswith("test_"):
        category = FileCategory.TEST
    elif ext in _TEXT_EXTENSIONS and language:
        category = FileCategory.SOURCE
    elif ext in _TEXT_EXTENSIONS:
        category = FileCategory.OTHER
    else:
        category = FileCategory.OTHER

    return category, language, False


