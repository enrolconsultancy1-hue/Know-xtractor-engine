class FileInventory:
    """Scans a repository directory into a filtered list of FileEntry objects."""

    def __init__(self, root: str) -> None:
        self.root = Path(root)
        self.settings = get_settings()

    def scan(self) -> list[FileEntry]:
        gitignore = _read_gitignore(self.root)
        entries: list[FileEntry] = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            # Prune ignored directories in-place.
            dirnames[:] = [
                d for d in dirnames
                if d not in _DEFAULT_IGNORES
                and not _matches_ignore(
                    str(Path(dirpath) / d).replace(str(self.root), "").lstrip("\\/"), gitignore
                )
            ]
            for fname in filenames:
                fpath = Path(dirpath) / fname
                rel = str(fpath.relative_to(self.root)).replace("\\", "/")
                if _matches_ignore(rel, gitignore):
                    continue
                try:
                    size = fpath.stat().st_size
                except OSError:
                    continue
                category, language, is_binary = classify_file(fpath, size)
                if size > self.settings.max_file_size_bytes:
                    # Oversized: skip content but record for reporting.
                    entries.append(FileEntry(
                        path=rel, category=category, language=language,
                        size=size, is_binary=True,
                    ))
                    continue
                entries.append(FileEntry(
                    path=rel, category=category, language=language,
                    size=size, is_binary=is_binary,
                ))
                if len(entries) >= self.settings.max_files_per_analysis:
                    break
            if len(entries) >= self.settings.max_files_per_analysis:
                break
        return entries

    @staticmethod
    def source_files(entries: list[FileEntry]) -> list[FileEntry]:
        return [e for e in entries if e.category == FileCategory.SOURCE and not e.is_binary]

    @staticmethod
    def config_files(entries: list[FileEntry]) -> list[FileEntry]:
        return [e for e in entries if e.category == FileCategory.CONFIG]

    @staticmethod
    def test_files(entries: list[FileEntry]) -> list[FileEntry]:
        return [e for e in entries if e.category == FileCategory.TEST]

    @staticmethod
    def doc_files(entries: list[FileEntry]) -> list[FileEntry]:
        return [e for e in entries if e.category == FileCategory.DOC]
